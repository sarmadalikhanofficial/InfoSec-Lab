def encrypt(text, shift=4):
    result = ""
    for char in text:
        if char.isupper():
            result += chr((ord(char) - 65 + shift) % 26 + 65)
        elif char.islower():
            result += chr((ord(char) - 97 + shift) % 26 + 97)
        else:
            result += char
    return result


def decrypt(text, shift=4):
    result = ""
    for char in text:
        if char.isupper():
            result += chr((ord(char) - 65 - shift) % 26 + 65)
        elif char.islower():
            result += chr((ord(char) - 97 - shift) % 26 + 97)
        else:
            result += char
    return result


message = input("Enter message to transmit: ")

encoded = encrypt(message, 4)
decoded = decrypt(encoded, 4)

print("Original:", message)
print("Encoded (Shift-4):", encoded)
print("Decoded:", decoded)
